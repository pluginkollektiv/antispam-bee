<?php
declare( strict_types=1 );

// phpcs:disable

use Composer\ClassMapGenerator\ClassMapGenerator;

$root = dirname( __DIR__ );

// Dev deps hold the generator. Absent on --no-dev installs → skip, don't fail.
$autoload = $root . '/vendor/autoload.php';
if ( ! is_file( $autoload ) ) {
	fwrite( STDERR, "vendor/autoload.php not found — skipping classmap generation.\n" );
	exit( 0 );
}
require $autoload;

if ( ! class_exists( ClassMapGenerator::class ) ) {
	fwrite( STDERR, "composer/class-map-generator not installed — skipping.\n" );
	exit( 0 );
}

$generator = new ClassMapGenerator();
$generator->scanPaths( $root . '/src' ); // only your own classes; vendor never enters
$classMap = $generator->getClassMap();
$classMap->sort(); // deterministic, diff-friendly output

$ambiguous = $classMap->getAmbiguousClasses();
if ( $ambiguous !== [] ) {
	fwrite( STDERR, "Ambiguous class definitions:\n" );
	foreach ( $ambiguous as $class => $paths ) {
		fwrite( STDERR, "  {$class}\n" );
	}
	exit( 1 );
}

$entries = '';
foreach ( $classMap->getMap() as $class => $path ) {
	$relative = substr( $path, strlen( $root ) ); // e.g. /src/Admin/Tab.php
	$entries  .= sprintf(
		"\t%s => __DIR__ . %s,\n",
		var_export( $class, true ),
		var_export( $relative, true )
	);
}

file_put_contents(
	$root . '/classmap.php',
	"<?php\n\n// Generated by bin/generate-classmap.php — do not edit.\n\nreturn array(\n{$entries});\n"
);

fwrite( STDOUT, sprintf( "Wrote classmap.php (%d classes).\n", $classMap->count() ) );
